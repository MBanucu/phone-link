"""Generate or check the mechanical views of `phone_link.actions`.

The registry in `phone_link.actions` is the only description of a command.
Four files are written from it:

- `bin/<id>` -- the resolver shim (every kind except ``tool``, whose body is
  the hand-written screenshot script);
- `lib/python/phone_link/commands/__init__.py` -- the name -> function map;
- the table in `docs/scripts.md` between the generated-region markers.

Run from the checkout:

    PYTHONPATH=lib/python python3 -m phone_link.registry_gen --check
    PYTHONPATH=lib/python python3 -m phone_link.registry_gen --write

`--check` is what the flake's `registry` and `gui-registry` checks run, and
`phone-link check-registry` runs it against the checkout automatically.
Standard library only.
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

from . import actions

DOCS_BEGIN = "<!-- BEGIN generated: scripts (phone_link.actions) -->"
DOCS_END = "<!-- END generated: scripts (phone_link.actions) -->"
WRITE_HINT = "run `PYTHONPATH=lib/python python3 -m phone_link.registry_gen --write`"

COMMANDS_DOC = '''"""The bin/ commands that live in Python, one function per script.

`bin/phone-net-status` and its siblings are shims that hand the script's name
to `python3 -m phone_link.commands`, so the name stays the contract: the
registry, the Nix wrappers and the tests all address the scripts, not modules.

Generated by `phone_link.registry_gen` from `phone_link.actions`; edit the
table, not this file.
"""'''

COMMANDS_MAIN = """def main(argv: list[str] | None = None) -> int:
    args = list(sys.argv[1:] if argv is None else argv)
    if not args:
        print(USAGE, end="", file=sys.stderr)
        return 2
    command, rest = args[0], args[1:]
    handler = COMMANDS.get(command)
    if handler is None:
        print(f"error: unknown command: {command}", file=sys.stderr)
        return 2
    return handler(rest)
"""


def shim_text(script: actions.Action) -> str:
    """The exact wrapper for one entry point."""
    if script.kind == "action":
        return f"""#!/usr/bin/env bash
# {script.id} lives in ../lib/python/phone_link/commands (one function per
# script). This wrapper only resolves the package next to the checkout or the
# store install, then hands over to it.
set -eu

here=$(dirname -- "$(readlink -f -- "$0")")
for candidate in "$here/../lib/python" "$here/../share/phone-link/lib/python"; do
  if [ -d "$candidate/phone_link" ]; then
    export PYTHONPATH="$candidate${{PYTHONPATH:+:$PYTHONPATH}}"
    break
  fi
done
export PYTHONDONTWRITEBYTECODE=1
shim="$here/${{0##*/}}"
export PHONE_LINK_SHIM="$shim"
exec python3 -m phone_link.commands {script.id} "$@"
"""
    if script.kind == "doctor":
        return """#!/usr/bin/env bash
# The doctor lives in ../lib/python/phone_doctor (one module per symptom group).
# This wrapper only resolves the package next to the checkout or the store
# install, then hands over to it.
set -eu

here=$(dirname -- "$(readlink -f -- "$0")")
export PYTHONPATH="$here/../lib/python${PYTHONPATH:+:$PYTHONPATH}"
export PYTHONDONTWRITEBYTECODE=1
exec python3 -m phone_doctor "$@"
"""
    if script.kind == "cli":
        return """#!/usr/bin/env bash
# CLI half of the shared action registry: list, run and check the same actions
# the GUI shows. The core lives in ../lib/python/phone_link (checkout) or
# ../share/phone-link/lib/python (store install).
set -eu

here=$(dirname -- "$(readlink -f -- "$0")")
for candidate in "$here/../lib/python" "$here/../share/phone-link/lib/python"; do
  if [ -d "$candidate/phone_link" ]; then
    export PYTHONPATH="$candidate${PYTHONPATH:+:$PYTHONPATH}"
    break
  fi
done
export PYTHONDONTWRITEBYTECODE=1
exec python3 -m phone_link "$@"
"""
    if script.kind == "gui":
        return """#!/usr/bin/env bash
# Launch the GTK4/libadwaita control panel. The Python packages live in
# ../lib/python (checkout) or ../share/phone-link-gui/lib/python (store).
set -eu

here=$(dirname -- "$(readlink -f -- "$0")")
for candidate in "$here/../lib/python" "$here/../share/phone-link-gui/lib/python"; do
  if [ -d "$candidate/phone_link_gui" ]; then
    export PYTHONPATH="$candidate${PYTHONPATH:+:$PYTHONPATH}"
    break
  fi
done
export PYTHONDONTWRITEBYTECODE=1
exec python3 -m phone_link_gui "$@"
"""
    raise ValueError(f"{script.id}: no shim template for kind {script.kind}")


def commands_text() -> str:
    """The generated `commands/__init__.py`."""
    entries = [script for script in actions.SCRIPTS if script.kind == "action"]
    modules = sorted({script.module.rsplit(".", 1)[1] for script in entries})
    mapping = "\n".join(
        f'    "{script.id}": {script.module.rsplit(".", 1)[1]}.{script.function},'
        for script in entries
    )
    return (
        COMMANDS_DOC
        + "\n\nfrom __future__ import annotations\n\nimport sys\n\n"
        + f"from . import {', '.join(modules)}\n\n"
        + "COMMANDS = {\n"
        + mapping
        + "\n}\n\n"
        + 'USAGE = "usage: phone_link.commands <command> [options]'
        + '\\n\\ncommands:\\n" + "".join(\n'
        + '    f"  {name}\\n" for name in COMMANDS\n'
        + ")\n\n\n"
        + COMMANDS_MAIN
    )


def docs_table() -> str:
    """The generated table rows, header included."""
    rows = ["| script | what it does |", "|---|---|"]
    for script in actions.SCRIPTS:
        if script.kind not in actions.ACTION_KINDS:
            continue
        rows.append(f"| `{script.id}` | {script.doc} |")
        for variant in script.variants:
            if not variant.doc:
                continue
            call = " ".join((script.id, *variant.args))
            rows.append(f"| `{call}` | {variant.doc} |")
    return "\n".join(rows) + "\n"


def _replace_region(text: str, begin: str, end: str, body: str) -> str | None:
    head, marker, rest = text.partition(begin)
    if not marker:
        return None
    _old, closing, tail = rest.partition(end)
    if not closing:
        return None
    return head + begin + "\n" + body + end + tail


def _check_file(path: Path, expected: str, problems: list[str]) -> None:
    try:
        actual = path.read_text(encoding="utf-8")
    except OSError as exc:
        problems.append(f"{path}: cannot read: {exc}")
        return
    if actual != expected:
        problems.append(f"{path}: out of date ({WRITE_HINT})")


def check(root: str | os.PathLike[str]) -> list[str]:
    """Every generated file agrees with the table; an empty list is success."""
    base = Path(root)
    problems: list[str] = []
    source = (base / "docs" / "scripts.md").is_file()

    if source and (base / "bin").is_dir():
        expected = sorted(script.id for script in actions.SCRIPTS)
        actual = sorted(
            path.name for path in (base / "bin").iterdir() if path.is_file()
        )
        missing = sorted(set(expected) - set(actual))
        extra = sorted(set(actual) - set(expected))
        if missing:
            problems.append("bin/: missing shims: " + ", ".join(missing))
        if extra:
            problems.append("bin/: shims without a table entry: " + ", ".join(extra))
        for script in actions.SCRIPTS:
            path = base / "bin" / script.id
            if not path.is_file():
                continue
            if not os.access(path, os.X_OK):
                problems.append(f"bin/{script.id}: not executable")
            if script.kind == "tool":
                # The screenshot tool is hand-written shell; the table only
                # promises that it exists and is packed.
                continue
            _check_file(path, shim_text(script), problems)

    commands = base / "lib" / "python" / "phone_link" / "commands" / "__init__.py"
    if commands.is_file():
        _check_file(commands, commands_text(), problems)

    docs = base / "docs" / "scripts.md"
    if docs.is_file():
        text = docs.read_text(encoding="utf-8")
        expected = _replace_region(text, DOCS_BEGIN, DOCS_END, docs_table())
        if expected is None:
            problems.append(
                f"docs/scripts.md: missing the generated table markers ({WRITE_HINT})"
            )
        elif expected != text:
            problems.append(f"docs/scripts.md: table is out of date ({WRITE_HINT})")
    return problems


def write(root: str | os.PathLike[str]) -> list[str]:
    """Write every generated file from the table; returns what was rewritten."""
    base = Path(root)
    changed: list[str] = []

    for script in actions.SCRIPTS:
        if script.kind == "tool":
            continue
        path = base / "bin" / script.id
        text = shim_text(script)
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8")
            changed.append(str(path))
        if not os.access(path, os.X_OK):
            path.chmod(path.stat().st_mode | 0o111)

    commands = base / "lib" / "python" / "phone_link" / "commands" / "__init__.py"
    text = commands_text()
    if not commands.is_file() or commands.read_text(encoding="utf-8") != text:
        commands.write_text(text, encoding="utf-8")
        changed.append(str(commands))

    docs = base / "docs" / "scripts.md"
    if docs.is_file():
        current = docs.read_text(encoding="utf-8")
        updated = _replace_region(current, DOCS_BEGIN, DOCS_END, docs_table())
        if updated is None:
            raise SystemExit(
                f"docs/scripts.md: add {DOCS_BEGIN!r} and {DOCS_END!r} around the table"
            )
        if updated != current:
            docs.write_text(updated, encoding="utf-8")
            changed.append(str(docs))
    return changed


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="phone_link.registry_gen",
        description="Generate or check the shims, COMMANDS and docs from actions.py.",
    )
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true", help="fail on disagreement")
    mode.add_argument(
        "--write", action="store_true", help="rewrite the generated files"
    )
    parser.add_argument(
        "--root",
        default=str(Path(__file__).resolve().parents[3]),
        help="checkout root (default: the one beside this package)",
    )
    args = parser.parse_args(argv)

    if args.check:
        problems = check(args.root)
        if problems:
            for problem in problems:
                print(f"error: {problem}", file=sys.stderr)
            return 1
        print(f"registry files ok: {len(actions.SCRIPTS)} scripts")
        return 0

    changed = write(args.root)
    if changed:
        for path in changed:
            print(f"wrote {path}")
    else:
        print("registry files already up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
